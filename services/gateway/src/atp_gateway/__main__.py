"""``python -m atp_gateway`` starts the gateway with uvicorn.

``python -m atp_gateway keygen [--write .env] [--keys-dir DIR]`` generates the
required keys; ``keygen --rotate --env .env`` rotates the grant signing key.
"""

from __future__ import annotations

import argparse
import contextlib
import logging
import sys
from pathlib import Path

import uvicorn

from atp_core import new_secret_key, show_unversioned_file_warnings
from atp_gateway.app import create_app
from atp_gateway.grant_keys import (
    KEYS_DIR_ENV,
    KID_ENV,
    generate_grant_key,
    read_env_file,
    rotate_grant_key,
)
from atp_gateway.settings import GatewaySettings

DEFAULT_KEYS_DIR = "atp-keys"


def keygen(argv: list[str]) -> None:
    """Generate gateway keys, or rotate the grant signing key.

    The operator key is a shared secret and goes into the env file. The grant
    signing key is an Ed25519 key pair written to ``--keys-dir`` (private key
    mode 0600); the env file names its directory and key id only. Writing to a
    file avoids shell-redirection encoding surprises (Windows PowerShell 5
    writes UTF-16 with ``>``) and refuses to overwrite an existing file.
    """
    parser = argparse.ArgumentParser(prog="atp-gateway keygen")
    parser.add_argument(
        "--write", metavar="PATH", help="write to PATH (e.g. .env); never overwrites"
    )
    parser.add_argument(
        "--keys-dir",
        metavar="DIR",
        help=f"where grant key files go (default: {DEFAULT_KEYS_DIR}/ next to --write, "
        "or in the current directory)",
    )
    parser.add_argument(
        "--rotate",
        action="store_true",
        help="make a new active grant key in the env file given by --env; the old public "
        "key keeps verifying for one grant TTL",
    )
    parser.add_argument("--env", metavar="PATH", help="env file to rotate (with --rotate)")
    args = parser.parse_args(argv)
    if args.rotate:
        if not args.env:
            sys.exit("--rotate needs --env PATH (the .env that holds ATP_GRANT_SIGNING_KID)")
        env_path = Path(args.env)
        keys_dir = args.keys_dir or read_env_file(env_path).get(KEYS_DIR_ENV, "")
        if not keys_dir:
            sys.exit(f"{env_path} has no {KEYS_DIR_ENV}; pass --keys-dir")
        try:
            old, new = rotate_grant_key(Path(keys_dir), env_path)
        except (OSError, ValueError) as exc:
            sys.exit(f"cannot rotate: {exc}")
        print(
            f"rotated grant signing key {old} -> {new} in {env_path}; restart the gateway. "
            f"Grants signed by {old} verify for one grant TTL more."
        )
        return
    if args.write is not None and Path(args.write).exists():
        sys.exit(f"{args.write} already exists; refusing to overwrite keys")
    base = Path(args.write).parent if args.write is not None else Path.cwd()
    keys_dir = Path(args.keys_dir) if args.keys_dir else base / DEFAULT_KEYS_DIR
    keys_dir = keys_dir.resolve()
    kid = generate_grant_key(keys_dir)
    lines = [
        "# generated by: atp keygen  (never commit this file or the keys directory)",
        f"ATP_OPERATOR_KEY={new_secret_key()}",
        f"{KEYS_DIR_ENV}={keys_dir}",
        f"{KID_ENV}={kid}",
    ]
    body = "\n".join(lines) + "\n"
    if args.write is None:
        print(body, end="")
        return
    path = Path(args.write)
    path.write_text(body, encoding="utf-8", newline="\n")
    with contextlib.suppress(OSError):
        path.chmod(0o600)
    print(
        f"wrote {path} and the grant key {kid} in {keys_dir} "
        "(keys are not shown; open the file to read them)"
    )


def main() -> None:
    if len(sys.argv) > 1 and sys.argv[1] == "keygen":
        keygen(sys.argv[2:])
        return
    show_unversioned_file_warnings()
    parser = argparse.ArgumentParser(prog="atp-gateway")
    parser.add_argument("--host", default="127.0.0.1")
    parser.add_argument("--port", type=int, default=8000)
    parser.add_argument("--log-level", default="info")
    args = parser.parse_args()
    logging.basicConfig(level=args.log_level.upper())
    uvicorn.run(
        create_app(GatewaySettings()), host=args.host, port=args.port, log_level=args.log_level
    )


if __name__ == "__main__":
    main()
