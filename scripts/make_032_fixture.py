"""Build tests/upgrade/fixtures/home-0.3.2/ from a real agent-trust-plane 0.3.2.

    uv run --no-sync python scripts/make_032_fixture.py

Steps: create a throwaway venv with ``uv``, ``uv pip install
agent-trust-plane==0.3.2`` from PyPI, run ``atp demo --out DIR wrap`` in an
empty temp dir, export an evidence bundle for every recorded trace with the
0.3.2 ``atp evidence export``, and copy the result into the fixture.

Layout of the fixture (paths are renamed so git keeps them; the test copies
them back to their real names in tmp_path before use):

    dot-atp/                 the demo's .atp/ (root .gitignore ignores ``.atp/``)
      dot-gitignore          the home's own .gitignore (it ignores keys.env, atp.db)
      atp.db, keys.env, policies.yaml
    atp-mcp.yaml, atp-regression.yaml, notes/
    evidence/<trace>.json    bundles exported by 0.3.2
    traces.json              0.3.2 ``atp trace list --json``
    MANIFEST.json            what made it

The keys in keys.env are throwaway demo keys generated by this script's run.

Absolute machine paths are stripped: atp-mcp.yaml's upstream ``command``
becomes ``python3`` and ``NOTES_DIR`` becomes ``notes``. Output is not
byte-for-byte reproducible: 0.3.2 draws grant/trace ids, keys and timestamps
at random / from the clock and has no seed. Regenerating replaces the fixture.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

VERSION = "0.3.2"
ROOT = Path(__file__).resolve().parent.parent
DEST = ROOT / "tests" / "upgrade" / "fixtures" / f"home-{VERSION}"


def run(cmd: list[str], **kw: object) -> str:
    proc = subprocess.run(cmd, capture_output=True, text=True, **kw)  # type: ignore[call-overload]
    if proc.returncode != 0:
        sys.stderr.write(proc.stdout + proc.stderr)
        raise SystemExit(f"failed ({proc.returncode}): {' '.join(cmd)}")
    return str(proc.stdout)


def strip_paths(text: str, *paths: Path) -> str:
    for p in sorted({str(p) for p in paths}, key=len, reverse=True):
        text = text.replace(p, "<tmp>")
    return text


def main() -> None:
    with tempfile.TemporaryDirectory(prefix="atp032-") as tmp_s:
        tmp = Path(tmp_s)
        venv = tmp / "venv"
        run(["uv", "venv", "-q", "--python", "3.13", str(venv)])
        env = {**os.environ, "VIRTUAL_ENV": str(venv)}
        env.pop("ATP_HOME", None)
        run(["uv", "pip", "install", "-q", f"agent-trust-plane=={VERSION}"], env=env)
        atp = str(venv / ("Scripts/atp.exe" if os.name == "nt" else "bin/atp"))
        work = tmp / "work"
        work.mkdir()
        out = work / "demo"
        run([atp, "demo", "--out", str(out), "wrap"], cwd=work, env=env)
        home = out / ".atp"

        traces = json.loads(run([atp, "trace", "list", "--json", "--home", str(home)], env=env))
        bundles = out / "evidence"
        bundles.mkdir()
        for t in traces:
            tid = t["trace_id"]
            run(
                [
                    atp,
                    "evidence",
                    "export",
                    tid,
                    "--out",
                    str(bundles / f"{tid}.json"),
                    "--home",
                    str(home),
                ],
                cwd=out,
                env=env,
            )
        (out / "traces.json").write_text(json.dumps(traces, indent=2) + "\n", encoding="utf-8")

        # Strip absolute machine paths from the text files.
        mcp = out / "atp-mcp.yaml"
        text = mcp.read_text(encoding="utf-8")
        for line in text.splitlines():
            s = line.strip()
            if s.startswith("command:"):
                text = text.replace(line, line[: line.index("command:")] + "command: python3")
            elif s.startswith("NOTES_DIR:"):
                text = text.replace(line, line[: line.index("NOTES_DIR:")] + "NOTES_DIR: notes")
        mcp.write_text(text, encoding="utf-8")
        for f in out.rglob("*"):
            if f.is_file() and f.suffix in {".yaml", ".json", ".txt"}:
                raw = f.read_text(encoding="utf-8")
                clean = strip_paths(raw, tmp, tmp.resolve())
                if clean != raw:
                    f.write_text(clean, encoding="utf-8")
        leaks = [
            str(f.relative_to(out))
            for f in out.rglob("*")
            if f.is_file() and str(tmp).encode() in f.read_bytes()
        ]
        if leaks:
            raise SystemExit(f"absolute temp paths left in {leaks}")

        # Rename what git would drop, then replace the fixture.
        (home / ".gitignore").rename(home / "dot-gitignore")
        home.rename(out / "dot-atp")
        (out / "MANIFEST.json").write_text(
            json.dumps(
                {
                    "generator": "scripts/make_032_fixture.py",
                    "package": f"agent-trust-plane=={VERSION}",
                    "command": "atp demo --out <tmp> wrap",
                    "renamed": {"dot-atp": ".atp", "dot-atp/dot-gitignore": ".atp/.gitignore"},
                    "traces": [t["trace_id"] for t in traces],
                },
                indent=2,
            )
            + "\n",
            encoding="utf-8",
        )
        if DEST.exists():
            shutil.rmtree(DEST)
        DEST.parent.mkdir(parents=True, exist_ok=True)
        shutil.copytree(out, DEST)
    print(f"wrote {DEST.relative_to(ROOT)}")
    print(f"commit it with: git add -f {DEST.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
