"""The local ATP home: a directory that holds everything ``atp mcp wrap``
needs so that nothing has to be copied, exported or typed.

    .atp/
      atp.db          SQLite: credentials, delegations, grants, traces, ledger
      keys.env        ATP_OPERATOR_KEY and ATP_GRANT_SIGNING_KID, generated once, mode 600
      keys/           grant-<kid>.key (Ed25519, mode 600), grant-<kid>.pub, grant-<kid>.retired
      policies.yaml   optional declared policy sets (see docs/policies.md)

Location: ``$ATP_HOME`` if set, else ``./.atp``. Offline commands
(``regression add``, ``policy explain``, ``evidence export``) open the same
store directly; no HTTP, no operator key to paste. Treat the directory as
secret: whoever can read ``keys.env`` is the operator, and whoever can read
``keys/`` can mint execution grants.

A 0.3.x home kept an HMAC ``ATP_GRANT_SIGNING_KEY`` in ``keys.env``. ``ensure()``
(and ``settings()``) migrate it once: a new Ed25519 key is generated, then the
HMAC line is removed. Traces and evidence bundles are keyless hash chains, so
nothing recorded before the migration needs the old key to verify.
"""

from __future__ import annotations

import os
from datetime import datetime
from pathlib import Path

from atp_core import new_secret_key
from atp_gateway import GatewaySettings, Runtime, build_runtime
from atp_gateway.grant_keys import (
    KID_ENV,
    LEGACY_HMAC_ENV,
    generate_grant_key,
    private_key_path,
    read_env_file,
    rotate_grant_key,
    update_env_file,
    write_file_atomic,
)

KEYS_FILE = "keys.env"
KEYS_DIR = "keys"
_GITIGNORE_ENTRIES = ("keys.env", "keys/", "atp.db", "atp.db-*")
DB_FILE = "atp.db"
POLICY_FILE = "policies.yaml"


class AtpHome:
    def __init__(self, path: str | Path | None = None) -> None:
        raw = path or os.environ.get("ATP_HOME") or ".atp"
        self.path = Path(raw).expanduser().resolve()

    @property
    def keys_dir(self) -> Path:
        return self.path / KEYS_DIR

    @property
    def db_path(self) -> Path:
        return self.path / DB_FILE

    @property
    def keys_path(self) -> Path:
        return self.path / KEYS_FILE

    @property
    def policy_path(self) -> Path:
        return self.path / POLICY_FILE

    @property
    def exists(self) -> bool:
        return self.db_path.exists()

    def ensure(self) -> AtpHome:
        """Create the directory and keys if missing; migrate a 0.3.x HMAC grant
        key to Ed25519. Idempotent."""
        self.path.mkdir(parents=True, exist_ok=True)
        if not self.keys_path.exists():
            kid = generate_grant_key(self.keys_dir)
            text = (
                "# generated by atp; whoever reads this file is the operator\n"
                f"ATP_OPERATOR_KEY={new_secret_key()}\n"
                f"{KID_ENV}={kid}\n"
            )
            write_file_atomic(self.keys_path, text.encode("utf-8"), private=True)
        else:
            self.migrate_keys()
        self._ensure_gitignore()
        return self

    def migrate_keys(self) -> bool:
        """Give ``keys.env`` an Ed25519 grant key if it has none, and drop the
        0.3.x HMAC ``ATP_GRANT_SIGNING_KEY``. Returns True when it changed
        anything. The new key is written before ``keys.env`` is switched to it,
        so an interrupted run leaves either the old file or the new one."""
        env = read_env_file(self.keys_path)
        kid = env.get(KID_ENV, "")
        if kid:
            if not private_key_path(self.keys_dir, kid).exists():
                raise RuntimeError(
                    f"{self.keys_path} names grant key {kid}, but "
                    f"{private_key_path(self.keys_dir, kid)} is missing. Restore it, or "
                    f"remove the {KID_ENV} line to generate a new key."
                )
            if LEGACY_HMAC_ENV not in env:
                return False
            update_env_file(self.keys_path, set_values={}, remove=frozenset({LEGACY_HMAC_ENV}))
            return True
        new = generate_grant_key(self.keys_dir)
        update_env_file(
            self.keys_path, set_values={KID_ENV: new}, remove=frozenset({LEGACY_HMAC_ENV})
        )
        return True

    def rotate_grant_key(self, now: datetime | None = None) -> tuple[str, str]:
        """``atp keygen --rotate``: a new active grant key; the old public key
        keeps verifying for one grant TTL. Returns ``(old_kid, new_kid)``."""
        self.ensure()
        return rotate_grant_key(self.keys_dir, self.keys_path, now=now)

    def _ensure_gitignore(self) -> None:
        gitignore = self.path / ".gitignore"
        if not gitignore.exists():
            gitignore.write_text(
                "# secrets and local state; policies.yaml is meant to be committed\n"
                + "".join(f"{e}\n" for e in _GITIGNORE_ENTRIES),
                encoding="utf-8",
            )
            return
        text = gitignore.read_text(encoding="utf-8")
        present = {line.strip() for line in text.splitlines()}
        missing = [e for e in _GITIGNORE_ENTRIES if e not in present]
        if missing:
            sep = "" if text.endswith("\n") or not text else "\n"
            gitignore.write_text(text + sep + "".join(f"{e}\n" for e in missing), encoding="utf-8")

    def ensure_policy_file(self, version: str, description: str = "") -> bool:
        """Write a starter declared policy set if the home has none. Returns
        True when a file was written."""
        if self.policy_path.exists():
            return False
        text = f"""\
# Declared policy sets for this project (loaded next to the built-in payments sets).
# Every set always includes the kernel policies: delegation valid, capability held,
# resource in scope. Rules add argument-level limits on top. See docs/policies.md.
version: 1
policy_sets:
  - version: {version}
    description: {description or version}
    rules: []
    # examples (uncomment and adapt):
    #  - id: short-notes
    #    applies_to: {{tool: mcp.notes, action: write_note}}
    #    kind: argument_max_length
    #    argument: text
    #    max_length: 2000
    #  - id: never-delete
    #    applies_to: {{tool: mcp.notes, action: delete_note}}
    #    kind: deny
"""
        self.policy_path.write_text(text, encoding="utf-8")
        return True

    def keys(self) -> dict[str, str]:
        out = read_env_file(self.keys_path)
        missing = {"ATP_OPERATOR_KEY", KID_ENV} - set(out)
        if missing:
            raise RuntimeError(f"{self.keys_path} is missing {sorted(missing)}")
        return out

    def settings(
        self,
        *,
        enforcement_mode: str = "enforce",
        default_policy_set: str | None = None,
        external_tools: tuple[str, ...] = (),
    ) -> GatewaySettings:
        """Gateway settings for this home. Keys, database, enforcement mode and policy
        file come from the home, not from the environment or a ``.env``.

        ``external_tools`` (``atp mcp wrap`` passes its mapping tools) are appended to
        the external tool prefixes in effect: ``$ATP_EXTERNAL_TOOL_PREFIXES`` if set,
        else the default ``mcp.``. They add to that list; they do not override it.
        """
        self.migrate_keys()
        keys = self.keys()
        kwargs: dict[str, object] = {
            "database_path": str(self.db_path),
            "grant_keys_dir": str(self.keys_dir),
            "grant_signing_kid": keys[KID_ENV],
            "grant_signing_key": "",  # a stray 0.3.x $ATP_GRANT_SIGNING_KEY is ignored
            "operator_key": keys["ATP_OPERATOR_KEY"],
            "enforcement_mode": enforcement_mode,
            "policy_file": str(self.policy_path) if self.policy_path.exists() else "",
        }
        if default_policy_set:
            kwargs["default_policy_set"] = default_policy_set
        # _env_file=None: the home is authoritative; a stray .env must not override it.
        settings = GatewaySettings(_env_file=None, **kwargs)  # type: ignore[arg-type]
        if external_tools:
            # The wrapped proxy executes its mapped tools; the gateway only decides and
            # binds. They extend the prefixes already in effect ($ATP_EXTERNAL_TOOL_PREFIXES
            # or the default), never replace them.
            kwargs["external_tool_prefixes"] = ",".join(
                [*settings.external_tool_prefix_list(), *external_tools]
            )
            settings = GatewaySettings(_env_file=None, **kwargs)  # type: ignore[arg-type]
        return settings

    def open(self, **kwargs: str) -> Runtime:
        """Open the store for offline commands."""
        if not self.exists:
            raise FileNotFoundError(
                f"no ATP home at {self.path}; run `atp mcp wrap` first or set ATP_HOME"
            )
        return build_runtime(self.settings(**kwargs))
