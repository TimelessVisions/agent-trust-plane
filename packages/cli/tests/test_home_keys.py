def test_old_traces_and_evidence_verify_after_key_migration(tmp_path: Path) -> None:
    """Trace chains and evidence bundles are keyless SHA-256 chains, so moving
    the grant key from HMAC to Ed25519 leaves them verifiable. A 0.3 trace
    carries ``key_fingerprint`` (of the HMAC key) in its grant_issued event."""
    from atp_cli.home import AtpHome
    from atp_gateway.service import GATEWAY_ACTOR

    home = AtpHome(tmp_path / "h").ensure()
    rt = build_runtime(home.settings())
    trace_id = "0123456789ab"
    rt.trust_plane.traces.append(
        trace_id,
        EventType.GRANT_ISSUED,
        GATEWAY_ACTOR,
        {"grant_id": "xg_old", "single_use": True, "key_fingerprint": "f" * 16},
    )
    rt.close()
    _make_032_keys(home.path)
    for p in home.keys_dir.iterdir():
        p.unlink()
    home.keys_dir.rmdir()

    rt = AtpHome(tmp_path / "h").open()
    assert rt.trust_plane.traces.verify(trace_id).valid
    view = rt.trust_plane.get_trace(trace_id)
    ok, detail = verify_bundle(build_bundle(view).model_dump(mode="json"))
    assert ok, detail
    rt.close()


def test_home_rotation_keeps_old_grants_valid_for_one_ttl(tmp_path: Path) -> None:
    from atp_cli.home import AtpHome

    home = AtpHome(tmp_path / "h").ensure()
    rt = build_runtime(home.settings())
    now = utcnow()
    claims = new_grant_claims(
        trace_id="0123456789ab",
        decision_id="dec_1",
        envelope_id="env_1",
        action_hash="f" * 64,
        agent_id="a",
        policy_set_version="p",
        ttl_seconds=rt.settings.grant_ttl_seconds,
        now=now,
    )
    token = rt.trust_plane.signer.mint(claims)
    old_kid = rt.trust_plane.signer.kid
    rt.close()

    old, new = home.rotate_grant_key()
    assert old == old_kid and new != old_kid
    assert not private_key_path(home.keys_dir, old).exists()

    rt = build_runtime(AtpHome(tmp_path / "h").settings())  # restart after rotation
    assert rt.trust_plane.signer.kid == new
    assert rt.trust_plane.verifier.verify(token) == claims
    ttl = timedelta(seconds=rt.settings.grant_ttl_seconds)
    with pytest.raises(GrantError) as exc:
        rt.trust_plane.verifier.verify(token, now=utcnow() + ttl + timedelta(seconds=1))
    assert exc.value.reason_code is ReasonCode.GRANT_SIGNATURE_INVALID
    rt.close()


def test_keygen_rotate_on_the_home(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    from atp_cli.home import AtpHome
    from atp_cli.main import main

    home = AtpHome(tmp_path / "h").ensure()
    kid = read_env_file(home.keys_path)["ATP_GRANT_SIGNING_KID"]
    monkeypatch.setenv("ATP_HOME", str(home.path))
    with pytest.raises(SystemExit) as exc:
        main(["keygen", "--rotate"])
    assert exc.value.code in (0, None)
    new = read_env_file(home.keys_path)["ATP_GRANT_SIGNING_KID"]
    assert new != kid
    assert (home.keys_dir / f"grant-{kid}.retired").exists()


def test_keygen_write_and_rotate_a_serve_env(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """`atp keygen --write .env` then `atp keygen --rotate --env .env`: the
    persistent gateway loads the Ed25519 key, and after rotation still trusts
    the old public key for one grant TTL."""
    from atp_cli.main import main
    from atp_gateway import GatewaySettings

    monkeypatch.chdir(tmp_path)
    for var in ("ATP_GRANT_SIGNING_KID", "ATP_GRANT_KEYS_DIR", "ATP_GRANT_SIGNING_KEY"):
        monkeypatch.delenv(var, raising=False)
    with pytest.raises(SystemExit) as exc:
        main(["keygen", "--write", ".env"])
    assert exc.value.code in (0, None)
    env = read_env_file(tmp_path / ".env")
    assert set(env) == {"ATP_OPERATOR_KEY", "ATP_GRANT_KEYS_DIR", "ATP_GRANT_SIGNING_KID"}
    assert "PRIVATE KEY" not in (tmp_path / ".env").read_text(encoding="utf-8")
    assert _private(tmp_path / ".env")
    keys_dir = Path(env["ATP_GRANT_KEYS_DIR"])
    assert keys_dir == (tmp_path / "atp-keys").resolve()
    assert _private(private_key_path(keys_dir, env["ATP_GRANT_SIGNING_KID"]))

    def settings() -> GatewaySettings:
        return GatewaySettings(_env_file=".env", database_path=str(tmp_path / "atp.db"))

    rt = build_runtime(settings())
    old = rt.trust_plane.signer.kid
    assert old == env["ATP_GRANT_SIGNING_KID"]
    rt.close()

    with pytest.raises(SystemExit) as exc:
        main(["keygen", "--rotate", "--env", ".env"])
    assert exc.value.code in (0, None)
    rt = build_runtime(settings())
    assert rt.trust_plane.signer.kid != old
    assert rt.trust_plane.verifier.kids == {old, rt.trust_plane.signer.kid}
    rt.close()


def test_persistent_gateway_refuses_a_bare_hmac_key(tmp_path: Path) -> None:
    from atp_gateway import GatewaySettings
    from atp_gateway.settings import InsecureConfigurationError

    settings = GatewaySettings(
        _env_file=None,
        database_path=str(tmp_path / "atp.db"),
        grant_signing_key=new_secret_key(),
        operator_key=new_secret_key(),
    )
    with pytest.raises(InsecureConfigurationError, match="no longer supported"):
        build_runtime(settings)
    assert not (tmp_path / "atp.db").exists()
